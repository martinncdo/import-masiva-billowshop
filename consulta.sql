SELECT 
    a.CODIGOPARTICULAR AS codigo, 
    a.DESCRIPCION AS titulo, 
    (COALESCE(CAS.STOCKACTUAL, 0)
   - COALESCE(P.STOCKPEDIDOS, 0)
   - COALESCE(FAC.STOCKFACTURAS, 0)
   + COALESCE(REMIN.CANTIDAD, 0)
  ) AS REMANENTE,
    m.DESCRIPCION AS marca,
    a.COEFICIENTE AS impuesto,
    gsr.DESCRIPCION AS grupo_super_rubro,
    sr.DESCRIPCION super_rubro,
    a.precioventa1,
    a.codigomoneda,
    r.DESCRIPCION AS rubro
FROM ARTICULOS a
INNER JOIN RUBROS r  ON a.CODIGORUBRO = r.CODIGORUBRO
INNER JOIN SUPERRUBROS sr ON r.CODIGOSUPERRUBRO = sr.CODIGOSUPERRUBRO
INNER JOIN GRUPOSUPERRUBROS gsr ON sr.CODIGOGRUPOSUPERRUBRO = gsr.CODIGOGRUPOSUPERRUBRO 
INNER JOIN MARCAS m ON a.CODIGOMARCA = m.CODIGOMARCA 
LEFT JOIN (
    SELECT
        C1.CODIGOARTICULO,
        SUM(C1.STOCKACTUAL) AS STOCKACTUAL
    FROM CASILLEROS C1
    WHERE C1.CODIGODEPOSITO IN ('001','010','007','015','016','017')
    GROUP BY C1.CODIGOARTICULO
) CAS ON CAS.CODIGOARTICULO = A.CODIGOARTICULO
LEFT JOIN (
  SELECT c.CODIGOARTICULO, SUM(c.CANTIDAD) - SUM(c.CANTIDADREMITIDA) AS CANTIDAD
  FROM CUERPOCOMPROBANTES c
  INNER JOIN CABEZACOMPROBANTES ca ON c.NUMEROCOMPROBANTE = ca.NUMEROCOMPROBANTE 
  AND c.TIPOCOMPROBANTE = ca.TIPOCOMPROBANTE AND ca.ANULADA != 1
  AND ca.FECHACOMPROBANTE >= '2024-01-01' AND ca.FECHAMODIFICACION >= '2024-01-01'
  WHERE c.TIPOCOMPROBANTE = 'RI' 
  AND ca.ANULADA != 1 AND c.FECHAMODIFICACION  >= '2024-01-01'
  GROUP BY c.CODIGOARTICULO
) REMIN ON REMIN.CODIGOARTICULO = A.CODIGOARTICULO
LEFT JOIN (
    SELECT
        CUOP1.CODIGOARTICULO,
        SUM(CUOP1.CANTIDAD - CUOP1.CANTIDADREMITIDA) AS STOCKPEDIDOS
    FROM CUERPOPEDIDOS CUOP1
    INNER JOIN CABEZAPEDIDOS CAOP1 
        ON CUOP1.NUMEROCOMPROBANTE = CAOP1.NUMEROCOMPROBANTE
    INNER JOIN OPERACIONES OP1 
        ON CAOP1.OPERACION = OP1.CODIGOOPERACION
    WHERE OP1.COMPROMETESTOCK = 1
      AND CAOP1.ANULADA = 0
      AND CUOP1.CODIGODEPOSITO IN ('001','010','007','015','016','017')
    GROUP BY CUOP1.CODIGOARTICULO
) P ON P.CODIGOARTICULO = A.CODIGOARTICULO
LEFT JOIN (
    SELECT
        CU.CODIGOARTICULO,
        SUM(CU.CANTIDAD - CU.CANTIDADREMITIDA) AS STOCKFACTURAS
    FROM CUERPOCOMPROBANTES CU
    INNER JOIN CABEZACOMPROBANTES CAB 
        ON CAB.TIPOCOMPROBANTE = CU.TIPOCOMPROBANTE 
       AND CAB.NUMEROCOMPROBANTE = CU.NUMEROCOMPROBANTE
    WHERE CAB.ANULADA = 0
      AND CAB.TIPOCOMPROBANTE IN ('FA','FB','FC','FE','FT','FM')
      AND CU.CODIGODEPOSITO IN ('001','010','007','015','016','017')
    GROUP BY CU.CODIGOARTICULO
) FAC ON FAC.CODIGOARTICULO = A.CODIGOARTICULO
LEFT JOIN (
    SELECT 
        OC.CODIGOARTICULO, 
        MAX(CAC.FECHACOMPROBANTE) AS ULTIMAFECHA
    FROM CUERPOORDENESCOMPRAS OC
    INNER JOIN CABEZAORDENESCOMPRAS CAC 
        ON OC.NUMEROCOMPROBANTE = CAC.NUMEROCOMPROBANTE
    WHERE OC.ANULADO = 0
    GROUP BY OC.CODIGOARTICULO
) ULT_OC ON ULT_OC.CODIGOARTICULO = A.CODIGOARTICULO
WHERE (
      (COALESCE(CAS.STOCKACTUAL, 0)
       - COALESCE(P.STOCKPEDIDOS, 0)
       - COALESCE(FAC.STOCKFACTURAS, 0)
      ) >= 1
)
